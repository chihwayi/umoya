function renderIdentifier(name) {
  if (/^[a-z_][a-z0-9_]*$/.test(name) && !RESERVED_IDENTIFIERS.has(name)) {
    return name;
  }
  return `"${name.replace(/"/g, '""')}"`;
}

function escapeSqlString(value) {
  return value.replace(/'/g, "''");
}

function renderDefaultValue(column) {
  const defaultValue = column.defaultValue;
  if (!defaultValue) return null;

  if (defaultValue.kind === 'sql') {
    return defaultValue.value;
  }

  if (defaultValue.kind === 'boolean') {
    return defaultValue.value ? 'true' : 'false';
  }

  if (defaultValue.kind === 'number') {
    return String(defaultValue.value);
  }

  if (defaultValue.kind === 'array') {
    if (column.sqlType.endsWith('[]')) {
      return "'{}'";
    }
    if (column.sqlType === 'JSONB') {
      return "'[]'::jsonb";
    }
    return null;
  }

  if (defaultValue.kind === 'object') {
    if (column.sqlType === 'JSONB') {
      return "'{}'::jsonb";
    }
    return null;
  }

  if (defaultValue.kind === 'string') {
    if (column.sqlType === 'JSONB' && (defaultValue.value === '{}' || defaultValue.value === '[]')) {
      return `'${defaultValue.value}'::jsonb`;
    }
    if (column.sqlType.endsWith('[]') && (defaultValue.value === '{}' || defaultValue.value === '[]')) {
      return "'{}'";
    }
    return `'${escapeSqlString(defaultValue.value)}'`;
  }

  if (defaultValue.kind === 'raw') {
    if (column.sqlType === 'JSONB' && (defaultValue.value === '{}' || defaultValue.value === '[]')) {
      return `'${defaultValue.value}'::jsonb`;
    }
    if (column.sqlType.endsWith('[]') && (defaultValue.value === '{}' || defaultValue.value === '[]')) {
      return "'{}'";
    }
    return null;
  }

  return null;
}

function renderColumnDefinition(column, mode) {
  const parts = [renderIdentifier(column.rawColumnName), column.sqlType];

  if (column.generated && (!column.generatedStrategy || column.generatedStrategy === 'uuid')) {
    parts.push('PRIMARY KEY');
    parts.push('DEFAULT gen_random_uuid()');
    return parts.join(' ');
  }

  if (column.generated && (column.generatedStrategy === 'increment' || column.generatedStrategy === 'integer')) {
    parts.push('GENERATED BY DEFAULT AS IDENTITY');
    parts.push('PRIMARY KEY');
    return parts.join(' ');
  }

  if (column.primary) {
    parts.push('PRIMARY KEY');
  }

  const renderedDefault = renderDefaultValue(column);
  if (renderedDefault) {
    parts.push(`DEFAULT ${renderedDefault}`);
  }

  const shouldAddNotNull =
    !column.nullable &&
    !column.primary &&
    (!mode || mode === 'create' || renderedDefault);

  if (shouldAddNotNull) {
    parts.push('NOT NULL');
  }

  return parts.join(' ');
}

function escapeTemplateLiteral(input) {
  return input.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${');
}

async function main() {
  const entityTables = await extractEntityTables();
  const statements = [];

  for (const entityTable of [...entityTables.values()].sort((a, b) => a.tableName.localeCompare(b.tableName))) {
    const columns = entityTable.columnDefinitions
      .map((column) => `  ${renderColumnDefinition(column, 'create')}`)
      .join(',\n');

    statements.push(`CREATE TABLE IF NOT EXISTS ${renderIdentifier(entityTable.tableName)} (\n${columns}\n)`);
    for (const columnDefinition of entityTable.columnDefinitions) {
      statements.push(
        `ALTER TABLE ${renderIdentifier(entityTable.tableName)} ADD COLUMN IF NOT EXISTS ${renderColumnDefinition(columnDefinition, 'alter')}`,
      );
    }
  }

  const fileContents = `// Generated by scripts/generate-tenant-provisioning-alignment.mjs
// This bundle is presence-oriented: it backfills missing tables/columns to keep tenant provisioning aligned with the active entity model.

export const TENANT_ENTITY_ALIGNMENT_BUNDLE_VERSION = '${BUNDLE_VERSION}';

export const TENANT_ENTITY_ALIGNMENT_STATEMENTS = [
${statements.map((statement) => `  \`${escapeTemplateLiteral(statement)}\`,`).join('\n')}
];
`;

  await fs.mkdir(path.dirname(OUTPUT_PATH), { recursive: true });
  await fs.writeFile(OUTPUT_PATH, fileContents, 'utf8');

  console.log(
    JSON.stringify(
      {
        outputPath: OUTPUT_PATH,
        bundleVersion: BUNDLE_VERSION,
        statementCount: statements.length,
        tableCount: entityTables.size,
      },
      null,
      2,
    ),
  );
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
